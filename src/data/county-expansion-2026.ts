function siteSources(code: string, label: string, hasDocuments = true) {
  const record = {
    title: `${label} Remediation Database Record — ${code}`,
    publisher: "New York State Department of Environmental Conservation",
    url: `https://extapps.dec.ny.gov/cfmx/extapps/derexternal/haz/details.cfm?ProgNo=${code}`,
  };
  return hasDocuments
    ? [
        {
          title: `${label} Document Collection — ${code}`,
          publisher: "New York State Department of Environmental Conservation",
          url: `https://extapps.dec.ny.gov/data/DecDocs/${code}/`,
        },
        record,
        openData,
      ]
    : [record, openData];
}

function makeStory(seed: Seed): AtlasStory {
  return {
    lastReviewed: seed.lastReviewed ?? "August 4, 2026",
    background: seed.background,
    timeline: seed.timeline,
    documentedImpacts: seed.documentedImpacts,
    cleanupAndControls: seed.cleanupAndControls,
    presentDay: [
      seed.present,
      "The marker identifies the regulated site record; it does not define an exposure zone or assign conditions to every neighboring property.",
    ],
    researchNotes: [
      seed.note,
      "Use a verified agency boundary before replacing this facility point with parcel or plume geometry.",
    ],
  };
}

